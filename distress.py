def main() -> int:
    import argparse
    p = argparse.ArgumentParser(description="4 โมเดลคลาสสิกวัดความเสี่ยงและคุณภาพงบ")
    p.add_argument("ticker")
    p.add_argument("--ละเอียด", dest="detail", action="store_true",
                   help="แสดงตัวแปรทุกตัวที่ใช้คำนวณ")
    a = p.parse_args()

    from data_layer import get_stock_data
    d = get_stock_data(a.ticker)
    r = assess(d)

    name = (d.get("info", {}) or {}).get("longName", a.ticker)
    print(f"\n{'='*70}\n  {a.ticker} — {name}")
    sec = (d.get("info", {}) or {}).get("sector", "-")
    print(f"  กลุ่ม {sec}\n{'='*70}")

    for key in ("altman", "piotroski", "beneish", "ohlson"):
        m = r[key]
        print(f"\n{m['โมเดล']}")
        if not m["ใช้ได้"]:
            print(f"   ใช้ไม่ได้ — {m['เหตุผล']}")
            continue

        if key == "piotroski":
            print(f"   คะแนน {m['คะแนน']}/{m['เต็ม']}  ({m['ระดับ']})")
            if m.get("ข้อที่วัดไม่ได้"):
                print(f"   วัดไม่ได้ {m['ข้อที่วัดไม่ได้']} ข้อ")
            for it in m["รายข้อ"]:
                mark = "✓" if it["ผ่าน"] else ("—" if it["ผ่าน"] is None else "✗")
                print(f"     {mark} {it['ข้อ']:<34}{it['รายละเอียด']}")
        elif key == "ohlson":
            print(f"   คะแนน {m['คะแนน']:.2f} -> "
                  f"ความน่าจะเป็น {m['ความน่าจะเป็น (%)']:.1f}%  ({m['ระดับ']})")
        else:
            print(f"   คะแนน {m['คะแนน']:.2f}  ({m['ระดับ']})")
            if m.get("รุ่นสูตร"):
                print(f"   สูตรรุ่น : {m['รุ่นสูตร']}")
            if m.get("เกณฑ์"):
                print(f"   เกณฑ์ : {m['เกณฑ์']}")

        print(f"   {m['คำอธิบาย']}")
        if a.detail and m.get("ตัวแปร"):
            print("   ตัวแปรที่ใช้ :")
            for k, v in m["ตัวแปร"].items():
                print(f"     {k:<40}{v:>10.4f}")
        if m.get("หมายเหตุ"):
            print(f"   หมายเหตุ : {m['หมายเหตุ']}")

    print(f"\n{'-'*70}\n  สรุป : {r['สรุป']['ข้อความ']}")
    if r["สรุป"].get("ขัดแย้งกัน"):
        print()
        for line in r["สรุป"]["ขัดแย้งกัน"].replace("**", "").split("  \n"):
            print(f"  {line}")
    print(f"\n  ใช้ได้ {r['สรุป']['โมเดลที่ใช้ได้']}/4 โมเดล\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
