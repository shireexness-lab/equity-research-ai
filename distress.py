def _series(data: dict, key: str):
    """ดึงอนุกรมรายปีของบรรทัดหนึ่ง เรียงเก่า -> ใหม่"""
    df = data.get(KIND_OF.get(key, "balance"))
    s = find_row(df, LINES[key])
    if s is None:
        return pd.Series(dtype=float)
    return pd.to_numeric(pd.Series(s), errors="coerce").dropna()


def _val(data: dict, key: str, back: int = 0):
    """
    ค่าปีล่าสุด (back=0) หรือปีก่อนหน้า (back=1)

    คืน None เมื่อไม่มี — ผู้เรียกต้องตรวจทุกครั้ง ห้ามแทนด้วย 0
    """
    s = _series(data, key)
    if len(s) <= back:
        return None
    v = float(s.iloc[-1 - back])
    return v if np.isfinite(v) else None


