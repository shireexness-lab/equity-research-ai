# 2) Piotroski F-Score (2000) — งบปีนี้ดีขึ้นหรือแย่ลง
# ---------------------------------------------------------------------------

def piotroski_f(data: dict) -> dict:
    """
    ให้คะแนน 9 ข้อ ข้อละ 1 คะแนน ผ่านได้ 1 ไม่ผ่านได้ 0

    Piotroski พบว่าหุ้นราคาถูก (P/BV ต่ำ) ที่ได้ F-Score สูง
    ให้ผลตอบแทนดีกว่าหุ้นราคาถูกที่ได้ F-Score ต่ำอย่างมีนัยสำคัญ
    งานวิจัยนี้ตีพิมพ์ใน Journal of Accounting Research ปี 2000

    **จุดแข็งของโมเดลนี้คือใช้ข้อมูลน้อยและตีความง่าย**
    ทุกข้อเป็นคำถามใช่/ไม่ใช่ที่นักบัญชีตอบได้ทันทีโดยไม่ต้องใช้สูตรซับซ้อน

    9 ข้อ แบ่ง 3 กลุ่ม
        ทำกำไร (4)  : ROA เป็นบวก · เงินสดเป็นบวก · ROA ดีขึ้น · เงินสด > กำไร
        หนี้สิน (3) : หนี้ระยะยาวลด · สภาพคล่องดีขึ้น · ไม่เพิ่มทุน
        ประสิทธิภาพ (2) : อัตรากำไรขั้นต้นดีขึ้น · หมุนสินทรัพย์ดีขึ้น
    """
    out = {"โมเดล": "Piotroski F-Score", "ใช้ได้": False, "คะแนน": None,
           "เต็ม": 9, "ระดับ": None, "รายข้อ": [], "เหตุผล": ""}

    ta0, ta1 = _val(data, "สินทรัพย์รวม", 0), _val(data, "สินทรัพย์รวม", 1)
    ni0, ni1 = _val(data, "กำไรสุทธิ", 0), _val(data, "กำไรสุทธิ", 1)
    cfo0 = _val(data, "กระแสเงินสดดำเนินงาน", 0)

    if None in (ta0, ta1, ni0, ni1, cfo0) or not ta0 or not ta1:
        out["เหตุผล"] = "ต้องมีงบอย่างน้อย 2 ปี พร้อมสินทรัพย์ กำไรสุทธิ และกระแสเงินสด"
        return out

    roa0, roa1 = ni0 / ta0, ni1 / ta1
    items = []

    def add(name, ok, detail):
        """เก็บผลแต่ละข้อ — ok=None แปลว่าไม่มีข้อมูล ไม่ให้คะแนนและไม่หักคะแนน"""
        items.append({"ข้อ": name, "ผ่าน": ok, "รายละเอียด": detail})

    # ---- กลุ่มทำกำไร ----
    add("ROA เป็นบวก", roa0 > 0, f"ROA {roa0*100:.1f}%")
    add("กระแสเงินสดดำเนินงานเป็นบวก", cfo0 > 0, f"OCF {cfo0/1e6:,.0f} ล้าน")
    add("ROA ดีขึ้นจากปีก่อน", roa0 > roa1,
        f"{roa1*100:.1f}% -> {roa0*100:.1f}%")
    # เงินสดมากกว่ากำไร = กำไรมีเงินสดจริงรองรับ ไม่ใช่ตัวเลขทางบัญชี
    add("เงินสดมากกว่ากำไรสุทธิ", cfo0 > ni0,
        f"OCF {cfo0/1e6:,.0f} vs กำไร {ni0/1e6:,.0f} ล้าน")

    # ---- กลุ่มหนี้สินและสภาพคล่อง ----
    ltd0, ltd1 = _val(data, "หนี้ระยะยาว", 0), _val(data, "หนี้ระยะยาว", 1)
    if None not in (ltd0, ltd1):
        add("สัดส่วนหนี้ระยะยาวลดลง", (ltd0 / ta0) < (ltd1 / ta1),
            f"{ltd1/ta1*100:.1f}% -> {ltd0/ta0*100:.1f}% ของสินทรัพย์")
    else:
        add("สัดส่วนหนี้ระยะยาวลดลง", None, "ไม่มีข้อมูลหนี้ระยะยาว")

    ca0, cl0 = _val(data, "สินทรัพย์หมุนเวียน", 0), _val(data, "หนี้สินหมุนเวียน", 0)
    ca1, cl1 = _val(data, "สินทรัพย์หมุนเวียน", 1), _val(data, "หนี้สินหมุนเวียน", 1)
    if None not in (ca0, cl0, ca1, cl1) and cl0 and cl1:
        add("อัตราส่วนสภาพคล่องดีขึ้น", (ca0 / cl0) > (ca1 / cl1),
            f"{ca1/cl1:.2f} -> {ca0/cl0:.2f} เท่า")
    else:
        add("อัตราส่วนสภาพคล่องดีขึ้น", None, "ไม่มีข้อมูลสินทรัพย์/หนี้สินหมุนเวียน")

    sh = data.get("info", {}) or {}
    sh0 = sh.get("sharesOutstanding")
    try:
        # ใช้จำนวนหุ้นจากงบถ้ามี เพราะเทียบสองปีได้
        s_ser = find_row(data.get("income"), ["Diluted Average Shares",
                                              "Basic Average Shares"])
        s_ser = pd.to_numeric(pd.Series(s_ser), errors="coerce").dropna() \
            if s_ser is not None else pd.Series(dtype=float)
        if len(s_ser) >= 2:
            add("ไม่ได้เพิ่มทุน (จำนวนหุ้นไม่เพิ่ม)",
                float(s_ser.iloc[-1]) <= float(s_ser.iloc[-2]) * 1.01,
                f"{s_ser.iloc[-2]/1e6:,.0f} -> {s_ser.iloc[-1]/1e6:,.0f} ล้านหุ้น")
        else:
            add("ไม่ได้เพิ่มทุน (จำนวนหุ้นไม่เพิ่ม)", None,
                "ไม่มีจำนวนหุ้นย้อนหลัง 2 ปี")
    except Exception:
        add("ไม่ได้เพิ่มทุน (จำนวนหุ้นไม่เพิ่ม)", None, "อ่านจำนวนหุ้นไม่ได้")

    # ---- กลุ่มประสิทธิภาพ ----
    gp0, gp1 = _val(data, "กำไรขั้นต้น", 0), _val(data, "กำไรขั้นต้น", 1)
    rev0, rev1 = _val(data, "รายได้", 0), _val(data, "รายได้", 1)
    if None not in (gp0, gp1, rev0, rev1) and rev0 and rev1:
        add("อัตรากำไรขั้นต้นดีขึ้น", (gp0 / rev0) > (gp1 / rev1),
            f"{gp1/rev1*100:.1f}% -> {gp0/rev0*100:.1f}%")
    else:
        add("อัตรากำไรขั้นต้นดีขึ้น", None,
            "ไม่มีกำไรขั้นต้น (พบในธนาคารและบริษัทที่ไม่แยกต้นทุนขาย)")

    if None not in (rev0, rev1):
        add("การหมุนของสินทรัพย์ดีขึ้น", (rev0 / ta0) > (rev1 / ta1),
            f"{rev1/ta1:.2f} -> {rev0/ta0:.2f} รอบ")
    else:
        add("การหมุนของสินทรัพย์ดีขึ้น", None, "ไม่มีรายได้ย้อนหลัง 2 ปี")

    scored = [i for i in items if i["ผ่าน"] is not None]
    passed = sum(1 for i in scored if i["ผ่าน"])

    out.update({"ใช้ได้": True, "คะแนน": passed, "เต็ม": len(scored),
                "รายข้อ": items, "ข้อที่วัดไม่ได้": 9 - len(scored)})
    ratio = passed / max(len(scored), 1)
    out["ระดับ"] = ("แข็งแรง" if ratio >= 7 / 9 else
                    "ปานกลาง" if ratio >= 4 / 9 else "อ่อนแอ")
    out["คำอธิบาย"] = {
        "แข็งแรง": "งบการเงินดีขึ้นเกือบทุกด้านเทียบกับปีก่อน",
        "ปานกลาง": "มีทั้งด้านที่ดีขึ้นและแย่ลง",
        "อ่อนแอ": "งบการเงินแย่ลงในหลายด้านพร้อมกัน",
    }[out["ระดับ"]]
    return out


# ---------------------------------------------------------------------------
# 3) Beneish M-Score (1999) — ร่องรอยการตกแต่งตัวเลข
# ---------------------------------------------------------------------------

def beneish_m(data: dict) -> dict:
    """
    8 ตัวแปรเทียบปีนี้กับปีก่อน แล้วรวมเป็นคะแนนเดียว

        M = −4.84 + 0.920·DSRI + 0.528·GMI + 0.404·AQI + 0.892·SGI
            + 0.115·DEPI − 0.172·SGAI + 4.679·TATA − 0.327·LVGI

    **M > −1.78 = มีร่องรอยที่ควรตรวจสอบเพิ่ม**

    เรื่องที่ต้องเข้าใจให้ชัด
    --------------------------
    โมเดลนี้ **ไม่ได้บอกว่าบริษัทโกง** มันบอกว่าตัวเลขมีรูปแบบคล้ายกับ
    บริษัทที่เคยถูกพบว่าตกแต่งบัญชี ซึ่งบริษัทที่โตเร็วมากตามปกติ
    ก็เข้าเกณฑ์ได้เหมือนกัน (ยอดขายโต ลูกหนี้โต กำไรโต — เหมือนกันหมด)

    ใช้เป็น **ธงให้ไปอ่านหมายเหตุงบ** ไม่ใช่ข้อสรุป

    นักศึกษาจากมหาวิทยาลัย Cornell ใช้โมเดลนี้จับ Enron ได้ก่อนที่เรื่องจะแดง
    """
    out = {"โมเดล": "Beneish M-Score", "ใช้ได้": False, "คะแนน": None,
           "ระดับ": None, "ตัวแปร": {}, "เหตุผล": ""}

    if _is_financial(data):
        out["เหตุผล"] = "ใช้กับธนาคารและประกันไม่ได้ — โครงสร้างรายได้ต่างกันมาก"
        return out

    def two(key):
        return _val(data, key, 0), _val(data, key, 1)

    ar0, ar1 = two("ลูกหนี้")
    rev0, rev1 = two("รายได้")
    gp0, gp1 = two("กำไรขั้นต้น")
    ta0, ta1 = two("สินทรัพย์รวม")
    ca0, ca1 = two("สินทรัพย์หมุนเวียน")
    ppe0, ppe1 = two("ที่ดินอาคารอุปกรณ์สุทธิ")
    dep0, dep1 = two("ค่าเสื่อมและค่าตัดจำหน่าย")
    sga0, sga1 = two("ค่าใช้จ่ายขายบริหาร")
    ltd0, ltd1 = two("หนี้ระยะยาว")
    cl0, cl1 = two("หนี้สินหมุนเวียน")
    ni0 = _val(data, "กำไรสุทธิ")
    cfo0 = _val(data, "กระแสเงินสดดำเนินงาน")

    req = {"ลูกหนี้": (ar0, ar1), "รายได้": (rev0, rev1),
           "กำไรขั้นต้น": (gp0, gp1), "สินทรัพย์รวม": (ta0, ta1),
           "สินทรัพย์หมุนเวียน": (ca0, ca1),
           "ที่ดินอาคารอุปกรณ์": (ppe0, ppe1),
           "ค่าเสื่อม": (dep0, dep1), "ค่าใช้จ่ายขายบริหาร": (sga0, sga1)}
    missing = [k for k, (a, b) in req.items() if a is None or b is None]
    if missing or None in (ni0, cfo0):
        if ni0 is None or cfo0 is None:
            missing += ["กำไรสุทธิหรือกระแสเงินสด"]
        out["เหตุผล"] = "ข้อมูลไม่พอ ขาด : " + ", ".join(missing)
        return out
    if min(rev0, rev1, ta0, ta1) <= 0:
        out["เหตุผล"] = "รายได้หรือสินทรัพย์ไม่เป็นบวก"
        return out

    def safe(a, b, name):
        if b in (0, None) or a is None:
            raise ValueError(name)
        return a / b

    try:
        # DSRI  ลูกหนี้โตเร็วกว่ายอดขายไหม -> อาจรับรู้รายได้ที่ยังไม่ได้เงิน
        dsri = safe(ar0 / rev0, ar1 / rev1, "DSRI")
        # GMI   อัตรากำไรขั้นต้นแย่ลงไหม -> แรงจูงใจให้ตกแต่งเพิ่ม
        gmi = safe(gp1 / rev1, gp0 / rev0, "GMI")
        # AQI   สัดส่วนสินทรัพย์ที่ไม่ใช่ของจับต้องได้เพิ่มไหม -> อาจเลื่อนค่าใช้จ่ายไปเป็นสินทรัพย์
        soft0 = 1 - (ca0 + ppe0) / ta0
        soft1 = 1 - (ca1 + ppe1) / ta1
        aqi = safe(soft0, soft1, "AQI")
        # SGI   ยอดขายโตเร็วมากไหม -> บริษัทโตเร็วมีแรงกดดันให้รักษาการเติบโต
        sgi = rev0 / rev1
        # DEPI  อัตราค่าเสื่อมลดลงไหม -> ยืดอายุสินทรัพย์เพื่อลดค่าใช้จ่าย
        r0 = dep0 / (dep0 + ppe0)
        r1 = dep1 / (dep1 + ppe1)
        depi = safe(r1, r0, "DEPI")
        # SGAI  ค่าใช้จ่ายขายบริหารโตเร็วกว่ายอดขายไหม
        sgai = safe(sga0 / rev0, sga1 / rev1, "SGAI")
        # LVGI  หนี้สินโตเร็วกว่าสินทรัพย์ไหม
        lv0 = ((ltd0 or 0) + (cl0 or 0)) / ta0
        lv1 = ((ltd1 or 0) + (cl1 or 0)) / ta1
        lvgi = safe(lv0, lv1, "LVGI") if lv1 else 1.0
        # TATA  กำไรที่ไม่ใช่เงินสดมีสัดส่วนเท่าไร -> ตัวแปรที่มีน้ำหนักมากที่สุด
        tata = (ni0 - cfo0) / ta0
    except (ValueError, ZeroDivisionError) as e:
        out["เหตุผล"] = f"คำนวณตัวแปร {e} ไม่ได้ (ตัวหารเป็นศูนย์)"
        return out

    m = (-4.84 + 0.920 * dsri + 0.528 * gmi + 0.404 * aqi + 0.892 * sgi
         + 0.115 * depi - 0.172 * sgai + 4.679 * tata - 0.327 * lvgi)

    out.update({
        "ใช้ได้": True, "คะแนน": float(m),
        "เกณฑ์": {"ควรตรวจสอบเมื่อเกิน": -1.78},
        "ตัวแปร": {
            "DSRI ลูกหนี้เทียบยอดขาย": dsri,
            "GMI อัตรากำไรขั้นต้นแย่ลง": gmi,
            "AQI คุณภาพสินทรัพย์": aqi,
            "SGI การเติบโตยอดขาย": sgi,
            "DEPI อัตราค่าเสื่อมลดลง": depi,
            "SGAI ค่าใช้จ่ายขายบริหาร": sgai,
            "LVGI หนี้สินเพิ่ม": lvgi,
            "TATA กำไรที่ไม่ใช่เงินสด": tata,
        }})
    out["ระดับ"] = "ควรตรวจสอบ" if m > -1.78 else "ไม่พบร่องรอย"
    out["คำอธิบาย"] = (
        "ตัวเลขมีรูปแบบคล้ายบริษัทที่เคยถูกพบว่าตกแต่งบัญชี "
        "**ไม่ได้แปลว่าโกง** — บริษัทที่โตเร็วมากก็เข้าเกณฑ์ได้ "
        "ให้ใช้เป็นสัญญาณให้ไปอ่านหมายเหตุประกอบงบ"
        if m > -1.78 else
        "ไม่พบรูปแบบที่น่าสงสัยจากตัวเลขในงบ")
    return out


# ---------------------------------------------------------------------------
# 4) Ohlson O-Score (1980) — ความน่าจะเป็นที่จะล้มละลาย
# ---------------------------------------------------------------------------

def ohlson_o(data: dict) -> dict:
    """
    ต่างจาก Altman ตรงที่ให้ผลเป็น **ความน่าจะเป็น 0-100%** ไม่ใช่คะแนนดิบ

        P(ล้มละลาย) = 1 / (1 + e^(−O))

    Ohlson ใช้วิธีทางสถิติ (logistic regression) กับบริษัท 2,163 แห่ง
    ระหว่างปี 1970-1976 ซึ่งในสมัยนั้นถือว่าเป็นชุดข้อมูลที่ใหญ่มาก

    ข้อจำกัดที่ต้องบอก
    -------------------
    ตัวแปรแรกของสูตรดั้งเดิมคือ log(สินทรัพย์ / ดัชนีราคา GNP สหรัฐ)
    ซึ่งออกแบบมาเพื่อปรับค่าเงินเฟ้อของสหรัฐยุค 1970

    ระบบนี้ใช้ log(สินทรัพย์เป็นล้านหน่วยสกุลเงินนั้น) แทน
    **ผลที่ได้จึงเป็นค่าประมาณ ไม่ใช่ค่าตามสูตรต้นฉบับเป๊ะ**
    ควรใช้ดูอันดับเปรียบเทียบระหว่างหุ้น มากกว่าดูตัวเลข % แบบตายตัว
    """
    out = {"โมเดล": "Ohlson O-Score", "ใช้ได้": False, "คะแนน": None,
           "ความน่าจะเป็น (%)": None, "ระดับ": None, "เหตุผล": ""}

    if _is_financial(data):
        out["เหตุผล"] = "ใช้กับธนาคาร ประกัน และกองทุนไม่ได้"
        return out

    ta = _val(data, "สินทรัพย์รวม")
    tl = _val(data, "หนี้สินรวม")
    ca = _val(data, "สินทรัพย์หมุนเวียน")
    cl = _val(data, "หนี้สินหมุนเวียน")
    ni0, ni1 = _val(data, "กำไรสุทธิ", 0), _val(data, "กำไรสุทธิ", 1)
    cfo = _val(data, "กระแสเงินสดดำเนินงาน")

    missing = [n for n, v in (("สินทรัพย์รวม", ta), ("หนี้สินรวม", tl),
                              ("สินทรัพย์หมุนเวียน", ca),
                              ("หนี้สินหมุนเวียน", cl),
                              ("กำไรสุทธิปีนี้", ni0), ("กำไรสุทธิปีก่อน", ni1),
                              ("กระแสเงินสด", cfo)) if v is None]
    if missing or not ta or ta <= 0 or not cl or cl <= 0:
        out["เหตุผล"] = ("ข้อมูลไม่พอ ขาด : " + ", ".join(missing)) if missing \
            else "สินทรัพย์รวมหรือหนี้สินหมุนเวียนไม่เป็นบวก"
        return out

    size = np.log(max(ta / 1e6, 1e-6))
    tlta = tl / ta
    wcta = (ca - cl) / ta
    clca = cl / ca if ca else 0.0
    oeneg = 1.0 if tl > ta else 0.0            # ส่วนของผู้ถือหุ้นติดลบ
    nita = ni0 / ta
    futl = cfo / tl if tl else 0.0
    intwo = 1.0 if (ni0 < 0 and ni1 < 0) else 0.0   # ขาดทุน 2 ปีติด
    denom = abs(ni0) + abs(ni1)
    chin = (ni0 - ni1) / denom if denom else 0.0

    o = (-1.32 - 0.407 * size + 6.03 * tlta - 1.43 * wcta + 0.0757 * clca
         - 1.72 * oeneg - 2.37 * nita - 1.83 * futl + 0.285 * intwo
         - 0.521 * chin)
    prob = 1.0 / (1.0 + np.exp(-o))

    out.update({"ใช้ได้": True, "คะแนน": float(o),
                "ความน่าจะเป็น (%)": float(prob * 100),
                "ตัวแปร": {
                    "ขนาดสินทรัพย์ (log)": size,
                    "หนี้สิน/สินทรัพย์": tlta,
                    "เงินทุนหมุนเวียน/สินทรัพย์": wcta,
                    "หนี้สินหมุนเวียน/สินทรัพย์หมุนเวียน": clca,
                    "ส่วนทุนติดลบ": oeneg,
                    "กำไรสุทธิ/สินทรัพย์": nita,
                    "กระแสเงินสด/หนี้สิน": futl,
                    "ขาดทุน 2 ปีติด": intwo,
                    "การเปลี่ยนแปลงกำไร": chin,
                },
                "หมายเหตุ": "ใช้ log(สินทรัพย์เป็นล้าน) แทนดัชนีราคา GNP "
                            "ผลจึงเป็นค่าประมาณ เหมาะกับการเทียบอันดับ"})
    out["ระดับ"] = ("เสี่ยงสูง" if prob > 0.5 else
                    "เฝ้าระวัง" if prob > 0.2 else "ปลอดภัย")
    out["คำอธิบาย"] = {
        "เสี่ยงสูง": "โครงสร้างการเงินคล้ายบริษัทที่ล้มละลายในข้อมูลของ Ohlson",
        "เฝ้าระวัง": "มีสัญญาณบางอย่าง ควรดูร่วมกับ Altman Z",
        "ปลอดภัย": "ไม่พบรูปแบบที่บ่งชี้ความเสี่ยงล้มละลาย",
    }[out["ระดับ"]]
    return out


# ---------------------------------------------------------------------------
# รวมทุกโมเดล
# ---------------------------------------------------------------------------

def assess(data: dict) -> dict:
    """คำนวณทั้ง 4 โมเดล — ตัวไหนใช้ไม่ได้จะบอกเหตุผลไว้ในผลของตัวเอง"""
    res = {
        "altman": altman_z(data),
        "piotroski": piotroski_f(data),
        "beneish": beneish_m(data),
        "ohlson": ohlson_o(data),
    }

    # ---- สรุปรวมแบบอ่านง่าย ----
    warn = []
    a, p, b, o = res["altman"], res["piotroski"], res["beneish"], res["ohlson"]
    if a["ใช้ได้"] and a["ระดับ"] == "เสี่ยงสูง":
        warn.append("Altman Z ชี้ความเสี่ยงล้มละลาย")
    if o["ใช้ได้"] and o["ระดับ"] == "เสี่ยงสูง":
        warn.append(f"Ohlson O ให้ความน่าจะเป็นล้มละลาย {o['ความน่าจะเป็น (%)']:.0f}%")
    if b["ใช้ได้"] and b["ระดับ"] == "ควรตรวจสอบ":
        warn.append("Beneish M พบรูปแบบที่ควรตรวจสอบเพิ่ม")
    if p["ใช้ได้"] and p["ระดับ"] == "อ่อนแอ":
        warn.append(f"Piotroski F ได้ {p['คะแนน']}/{p['เต็ม']} — งบแย่ลงหลายด้าน")

    # ---- ตรวจว่าโมเดลขัดแย้งกันเองไหม ----
    #
    # ทำไมต้องมี : พบจริงกับ CPALL — Altman Z บอกเสี่ยงสูง
    # แต่ Piotroski ให้ 8/9 และ Ohlson ให้ความน่าจะเป็นล้มละลายแค่ 4.8%
    #
    # สาเหตุคือ Altman ให้น้ำหนักหนี้สินมาก บริษัทที่กู้มาซื้อกิจการ
    # (เช่น CPALL ซื้อ Makro และ Lotus) จะได้คะแนนต่ำทันที
    # ทั้งที่กระแสเงินสดยังแข็งแรงและจ่ายหนี้ได้สบาย
    #
    # ถ้าแสดงแต่คำเตือนของ Altman โดยไม่บอกว่าโมเดลอื่นเห็นต่าง
    # ผู้ใช้จะเข้าใจว่าบริษัทกำลังจะล้ม ซึ่งไม่ใช่สิ่งที่ข้อมูลบอก
    disagree = ""
    if a["ใช้ได้"] and o["ใช้ได้"]:
        a_bad = a["ระดับ"] == "เสี่ยงสูง"
        o_bad = o["ระดับ"] == "เสี่ยงสูง"
        p_good = p["ใช้ได้"] and p["ระดับ"] == "แข็งแรง"
        if a_bad and not o_bad:
            disagree = (f"**โมเดลเห็นไม่ตรงกัน** — Altman ชี้เสี่ยง "
                        f"แต่ Ohlson ให้ความน่าจะเป็นล้มละลายเพียง "
                        f"{o['ความน่าจะเป็น (%)']:.0f}%")
            if p_good:
                disagree += f" และ Piotroski ให้ {p['คะแนน']}/{p['เต็ม']}"
            disagree += ("  \nกรณีนี้มักเกิดกับบริษัทที่กู้มาลงทุนหรือซื้อกิจการ "
                         "ซึ่ง Altman ให้น้ำหนักหนี้สินสูงเป็นพิเศษ "
                         "ควรดูความสามารถจ่ายดอกเบี้ยและกระแสเงินสดประกอบ")
        elif o_bad and not a_bad:
            disagree = ("**โมเดลเห็นไม่ตรงกัน** — Ohlson ชี้เสี่ยง "
                        "แต่ Altman ยังอยู่ในเขตปลอดภัย "
                        "มักเกิดกับบริษัทที่เพิ่งขาดทุนติดกันแต่งบดุลยังแข็ง")

    n_ok = sum(1 for r in res.values() if r["ใช้ได้"])
    res["สรุป"] = {
        "โมเดลที่ใช้ได้": n_ok,
        "คำเตือน": warn,
        "ขัดแย้งกัน": disagree,
        "ข้อความ": ("ไม่พบสัญญาณเตือนจากโมเดลที่ใช้ได้" if not warn
                     else " · ".join(warn)),
    }
    return res


