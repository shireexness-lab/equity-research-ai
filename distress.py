# 1) Altman Z-Score (1968) — ความเสี่ยงล้มละลายภายใน 2 ปี
# ---------------------------------------------------------------------------

def altman_z(data: dict) -> dict:
    """
    สูตรมี 3 รุ่น ระบบเลือกให้ตามลักษณะบริษัท

    **รุ่นดั้งเดิม (Z)** — บริษัทผลิตที่จดทะเบียนในตลาด
        Z = 1.2·X1 + 1.4·X2 + 3.3·X3 + 0.6·X4 + 1.0·X5
        ปลอดภัย > 2.99 · เฝ้าระวัง 1.81-2.99 · เสี่ยง < 1.81

    **รุ่นตลาดเกิดใหม่ (Z'')** — บริษัทไม่ผลิต และหุ้นนอกสหรัฐ
        Z'' = 3.25 + 6.56·X1 + 3.26·X2 + 6.72·X3 + 1.05·X4
        ปลอดภัย > 5.85 · เฝ้าระวัง 4.15-5.85 · เสี่ยง < 4.15

        ตัดตัวแปร X5 (รายได้/สินทรัพย์) ออกโดยตั้งใจ เพราะอัตราการหมุนของ
        สินทรัพย์ต่างกันมากระหว่างอุตสาหกรรม ทำให้เปรียบเทียบข้ามกลุ่มไม่ได้
        และบวก 3.25 เพื่อให้เกณฑ์ตัดสินใช้ร่วมกันได้กับตลาดเกิดใหม่

    ตัวแปร
        X1 = เงินทุนหมุนเวียน / สินทรัพย์รวม     สภาพคล่อง
        X2 = กำไรสะสม / สินทรัพย์รวม             กำไรสะสมมาตลอดอายุบริษัท
        X3 = EBIT / สินทรัพย์รวม                 ความสามารถทำกำไรจากสินทรัพย์
        X4 = มูลค่าตลาด / หนี้สินรวม              เบาะรองรับจากมุมมองตลาด
        X5 = รายได้ / สินทรัพย์รวม                ประสิทธิภาพการใช้สินทรัพย์
    """
    out = {"โมเดล": "Altman Z-Score", "ใช้ได้": False, "คะแนน": None,
           "ระดับ": None, "รุ่นสูตร": None, "ตัวแปร": {}, "เหตุผล": ""}

    if _is_financial(data):
        out["เหตุผล"] = ("ใช้กับธนาคาร ประกัน และกองทุนไม่ได้ — "
                         "งบดุลคนละโครงสร้าง เงินฝากลูกค้าไม่ใช่หนี้ของกิจการ")
        return out

    ta = _val(data, "สินทรัพย์รวม")
    tl = _val(data, "หนี้สินรวม")
    ca = _val(data, "สินทรัพย์หมุนเวียน")
    cl = _val(data, "หนี้สินหมุนเวียน")
    re = _val(data, "กำไรสะสม")
    ebit = _val(data, "EBIT")
    rev = _val(data, "รายได้")
    mcap = (data.get("info", {}) or {}).get("marketCap")
    try:
        mcap = float(mcap) if mcap else None
    except (TypeError, ValueError):
        mcap = None

    missing = [n for n, v in (("สินทรัพย์รวม", ta), ("หนี้สินรวม", tl),
                              ("สินทรัพย์หมุนเวียน", ca), ("หนี้สินหมุนเวียน", cl),
                              ("กำไรสะสม", re), ("EBIT", ebit),
                              ("มูลค่าตลาด", mcap)) if v is None]
    if missing or not ta or ta <= 0 or not tl or tl <= 0:
        out["เหตุผล"] = ("ข้อมูลไม่พอ ขาด : " + ", ".join(missing)) if missing \
            else "สินทรัพย์รวมหรือหนี้สินรวมไม่เป็นบวก"
        return out

    x1 = (ca - cl) / ta
    x2 = re / ta
    x3 = ebit / ta
    x4 = mcap / tl

    us_manu = _is_manufacturer(data) and not str(data.get("ticker", "")).endswith(".BK")
    if us_manu and rev:
        x5 = rev / ta
        z = 1.2 * x1 + 1.4 * x2 + 3.3 * x3 + 0.6 * x4 + 1.0 * x5
        lo, hi, ver = 1.81, 2.99, "ดั้งเดิม (บริษัทผลิตในตลาดสหรัฐ)"
        out["ตัวแปร"] = {"X1 เงินทุนหมุนเวียน/สินทรัพย์": x1,
                         "X2 กำไรสะสม/สินทรัพย์": x2,
                         "X3 EBIT/สินทรัพย์": x3,
                         "X4 มูลค่าตลาด/หนี้สิน": x4,
                         "X5 รายได้/สินทรัพย์": x5}
    else:
        z = 3.25 + 6.56 * x1 + 3.26 * x2 + 6.72 * x3 + 1.05 * x4
        lo, hi, ver = 4.15, 5.85, "ตลาดเกิดใหม่ Z'' (4 ตัวแปร)"
        out["ตัวแปร"] = {"X1 เงินทุนหมุนเวียน/สินทรัพย์": x1,
                         "X2 กำไรสะสม/สินทรัพย์": x2,
                         "X3 EBIT/สินทรัพย์": x3,
                         "X4 มูลค่าตลาด/หนี้สิน": x4}

    out.update({"ใช้ได้": True, "คะแนน": float(z), "รุ่นสูตร": ver,
                "เกณฑ์": {"ปลอดภัยเมื่อเกิน": hi, "เสี่ยงเมื่อต่ำกว่า": lo}})
    out["ระดับ"] = ("ปลอดภัย" if z > hi else
                    "เฝ้าระวัง" if z >= lo else "เสี่ยงสูง")
    out["คำอธิบาย"] = {
        "ปลอดภัย": "โครงสร้างการเงินแข็งแรง โอกาสล้มละลายใน 2 ปีต่ำ",
        "เฝ้าระวัง": "อยู่ในเขตคาบเกี่ยว ควรดูแนวโน้มหลายปีประกอบ",
        "เสี่ยงสูง": "อยู่ในเขตที่บริษัทล้มละลายในอดีตส่วนใหญ่เคยอยู่",
    }[out["ระดับ"]]
    return out


