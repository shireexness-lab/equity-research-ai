_FIN_WORDS = ("bank", "financial", "insurance", "capital markets",
              "credit services", "asset management", "mortgage",
              "reit", "real estate investment trust")


def _is_financial(data: dict) -> bool:
    """
    ธนาคาร ประกัน หรือกองทุนหรือไม่

    สำคัญมาก เพราะ Altman และ Ohlson **ใช้กับกลุ่มนี้ไม่ได้เลย**
    งบดุลธนาคารมีหนี้สิน 90% ของสินทรัพย์เป็นเรื่องปกติ (เงินฝากลูกค้า)
    ถ้าเอาไปเข้าสูตร จะออกมาว่าธนาคารทุกแห่งกำลังจะล้มละลาย
    """
    info = data.get("info", {}) or {}
    text = f"{info.get('sector') or ''} {info.get('industry') or ''}".lower()
    return any(w in text for w in _FIN_WORDS)


def _is_manufacturer(data: dict) -> bool:
    """ผลิตสินค้าหรือไม่ — ใช้เลือกสูตร Altman รุ่นดั้งเดิม"""
    info = data.get("info", {}) or {}
    sec = str(info.get("sector") or "").lower()
    return sec in ("industrials", "basic materials", "consumer cyclical",
                   "consumer defensive", "energy", "technology", "healthcare")


