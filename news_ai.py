# คำที่กลับความหมายของคำถัดไป
NEGATORS = ("ไม่", "ยกเลิก", "ปฏิเสธ", "ระงับ", "not ", "no ", "avoid", "cancel")


def _norm(t):
    return re.sub(r"\s+", " ", str(t or "")).strip().lower()


def score_headline(title: str) -> dict:
    """
    ให้คะแนนหัวข้อข่าว 1 หัวข้อ

    คืน : คะแนน · ประเภท · คำที่เจอ
    """
    t = _norm(title)
    hits, total = [], 0.0

    for lex in (LEX_POS, LEX_NEG):
        for word, w in lex.items():
            wl = word.lower()
            if wl not in t:
                continue
            # ตรวจคำปฏิเสธที่อยู่ข้างหน้าไม่เกิน 12 ตัวอักษร
            # เช่น "ไม่ขาดทุน" ต้องไม่ถูกนับเป็นข่าวร้าย
            i = t.find(wl)
            before = t[max(0, i - 12):i]
            flip = any(n.strip() in before for n in NEGATORS)
            val = -w if flip else w
            total += val
            hits.append({"คำ": word, "น้ำหนัก": val,
                         "กลับความหมาย": flip})

    # จำกัดคะแนนไม่ให้พาดหัวที่มีคำเยอะ ๆ ครองผลทั้งหมด
    total = float(np.clip(total, -5, 5))
    kind = "Positive" if total >= 0.8 else "Negative" if total <= -0.8 else "Neutral"
    return {"คะแนน": total, "ประเภท": kind, "คำที่เจอ": hits}


def analyze(ticker: str, limit: int = 30, items=None) -> dict:
    """
    วิเคราะห์ข่าวของหุ้นตัวหนึ่ง

    items : ถ้าส่งรายการข่าวมาเอง จะไม่ดึงใหม่ (ใช้ตอนทดสอบหรือมีข่าวอยู่แล้ว)
    """
    if items is None:
        try:
            import news as NW
            got = NW.headlines(ticker, limit=limit)
            items = got.get("รายการ") or []
            links = {"ลิงก์ SET": got.get("ลิงก์ SET", "")}
        except Exception as e:
            return {"ใช้ได้": False, "เหตุผล": f"ดึงข่าวไม่สำเร็จ : {e}",
                    "จำนวนข่าว": 0}
    else:
        links = {}

    if not items:
        return {"ใช้ได้": False, "จำนวนข่าว": 0,
                "เหตุผล": "ไม่พบข่าวสำหรับหุ้นตัวนี้ — "
                          "ข่าวหุ้นไทยส่วนใหญ่อยู่บนเว็บ SET ซึ่งไม่เปิด API",
                **links}

    rows = []
    for it in items:
        s = score_headline(it.get("หัวข้อ", ""))
        rows.append({
            "วันที่": it.get("วันที่", ""),
            "หัวข้อ": it.get("หัวข้อ", ""),
            "ประเภท": s["ประเภท"],
            "คะแนน": s["คะแนน"],
            "คำที่จับได้": ", ".join(h["คำ"] for h in s["คำที่เจอ"]) or "—",
            "ที่มา": it.get("ที่มา", ""),
            "ลิงก์": it.get("ลิงก์", ""),
        })
    df = pd.DataFrame(rows)

    pos = int((df["ประเภท"] == "Positive").sum())
    neg = int((df["ประเภท"] == "Negative").sum())
    neu = int((df["ประเภท"] == "Neutral").sum())

    # ---- Impact Score : -100 ถึง +100 ----
    # ให้น้ำหนักข่าวใหม่มากกว่าข่าวเก่า เพราะข่าวเดือนที่แล้วราคาซึมซับไปแล้ว
    # ใช้การลดหลั่นแบบเรขาคณิต : ข่าวล่าสุดน้ำหนัก 1.0 ถัดไป 0.93 ...
    w = np.power(0.93, np.arange(len(df)))
    raw = float(np.sum(df["คะแนน"].values * w) / max(np.sum(w), 1e-9))
    impact = float(np.clip(raw * 20, -100, 100))

    mood = ("บวกชัดเจน" if impact >= 40 else "ค่อนไปทางบวก" if impact >= 15 else
            "กลาง ๆ" if impact > -15 else
            "ค่อนไปทางลบ" if impact > -40 else "ลบชัดเจน")

    return {
        "ใช้ได้": True,
        "ticker": ticker,
        "จำนวนข่าว": len(df),
        "บวก": pos, "ลบ": neg, "กลาง": neu,
        "Impact Score": impact,
        "อารมณ์ข่าว": mood,
        "ตาราง": df,
        "ข่าวบวกแรงสุด": df.nlargest(3, "คะแนน").to_dict("records"),
        "ข่าวลบแรงสุด": df.nsmallest(3, "คะแนน").to_dict("records"),
        "ครอบคลุมวันที่": (f"{df['วันที่'].min()} ถึง {df['วันที่'].max()}"
                           if df["วันที่"].astype(str).str.len().max() > 4 else "-"),
        **links,
    }


