def main() -> int:
    import argparse
    p = argparse.ArgumentParser(description="วิเคราะห์ข่าวและให้คะแนนผลกระทบ")
    p.add_argument("ticker")
    p.add_argument("--limit", type=int, default=30)
    a = p.parse_args()

    t = a.ticker.upper()
    print(f"\nกำลังดึงข่าว {t} ...")
    res = analyze(t, limit=a.limit)

    print("\n" + "=" * 76)
    print(f"  ข่าวของ {t}")
    print("=" * 76)
    if not res.get("ใช้ได้"):
        print(f"\n  {res.get('เหตุผล')}")
        if res.get("ลิงก์ SET"):
            print(f"  เปิดดูเองได้ที่ : {res['ลิงก์ SET']}\n")
        return 1

    print(f"\n  อ่าน {res['จำนวนข่าว']} ข่าว · ช่วง {res['ครอบคลุมวันที่']}")
    print(f"  Positive {res['บวก']} · Negative {res['ลบ']} · Neutral {res['กลาง']}")
    print(f"  Impact Score : {res['Impact Score']:+.0f} / 100  "
          f"({res['อารมณ์ข่าว']})")

    print(f"\n  {'วันที่':<12}{'ประเภท':<10}{'คะแนน':>7}  หัวข้อ")
    print("  " + "-" * 72)
    for _, r in res["ตาราง"].iterrows():
        mark = {"Positive": "+", "Negative": "-", "Neutral": " "}[r["ประเภท"]]
        print(f"  {str(r['วันที่'])[:10]:<12}{mark} {r['ประเภท']:<8}"
              f"{r['คะแนน']:>+7.1f}  {str(r['หัวข้อ'])[:52]}")
        if r["คำที่จับได้"] != "—":
            print(f"  {'':<12}  คำที่จับได้ : {r['คำที่จับได้']}")

    print("\n  ข้อจำกัดที่ต้องรู้")
    print("    • ให้คะแนนจากพจนานุกรมคำ ไม่เข้าใจการประชดหรือบริบท")
    print("    • อ่านได้แค่หัวข้อ ไม่ได้อ่านเนื้อข่าว")
    print(f"    • ดึงได้ {res['จำนวนข่าว']} ข่าว ซึ่งเป็นเพดานของแหล่งข้อมูลฟรี")
    print("      การได้ 10,000 ข่าวต้องใช้บริการข่าวเชิงพาณิชย์")
    if res.get("ลิงก์ SET"):
        print(f"\n  ข่าวครบถ้วนที่ SET : {res['ลิงก์ SET']}")
    print()
    return 0


if __name__ == "__main__":
    sys.exit(main())
